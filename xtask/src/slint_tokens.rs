//! Turns resolved design tokens into Slint globals (DESIGN.md §3.4).

use std::fmt::Write as _;

use anyhow::{Context as _, Result, anyhow, bail};
use serde_json::Value;

use crate::design_tokens::{DesignTokens, Theme};

/// Token groups and the Slint global each one becomes. `ref.*` (raw palette), `elevation.*` and
/// `motion.easing.*` are not exported: components must use semantic tokens, and Slint has no
/// property type for shadows or easing curves.
const GROUP_TO_GLOBAL: [(&str, &str); 8] = [
    ("color", "MellowColor"),
    ("component", "MellowComponent"),
    ("font", "MellowFont"),
    ("motion", "MellowMotion"),
    ("radius", "MellowRadius"),
    ("size", "MellowSize"),
    ("space", "MellowSpace"),
    ("type", "MellowType"),
];
const SKIPPED_TOKEN_TYPES: [&str; 2] = ["shadow", "cubicBezier"];

const GENERATED_FILE_HEADER: &str = "\
// Generated by `cargo xtask tokens` from design/tokens.json. Do not edit by hand.

export global MellowTheme {
    // Dark is the default theme (DESIGN.md §2).
    in-out property <bool> is-dark: true;
}

export struct MellowTypeStyle {
    font-family: string,
    font-size: length,
    font-weight: int,
    line-height: length,
    letter-spacing: length,
}
";

pub fn generate_slint_tokens(tokens: &DesignTokens) -> Result<String> {
    let mut output = String::from(GENERATED_FILE_HEADER);
    for (group, global_name) in GROUP_TO_GLOBAL {
        let group_prefix = format!("{group}.");
        writeln!(output, "\nexport global {global_name} {{")?;
        for (path, token) in &tokens.tokens_by_path {
            let Some(path_within_group) = path.strip_prefix(&group_prefix) else {
                continue;
            };
            if SKIPPED_TOKEN_TYPES.contains(&token.token_type.as_str()) {
                continue;
            }
            let (slint_type, slint_value) = slint_property(tokens, path, &token.token_type)
                .with_context(|| format!("token `{path}`"))?;
            writeln!(
                output,
                "    out property <{slint_type}> {}: {slint_value};",
                property_name(group, path_within_group)
            )?;
        }
        output.push_str("}\n");
    }
    Ok(output)
}

/// `rail.icon-size` → `rail-icon-size`; a leading digit (`3xs`) gets the group name (`space-3xs`).
fn property_name(group: &str, path_within_group: &str) -> String {
    let name = path_within_group.replace('.', "-");
    if name.starts_with(|first: char| first.is_ascii_digit()) {
        format!("{group}-{name}")
    } else {
        name
    }
}

fn slint_property(tokens: &DesignTokens, path: &str, token_type: &str) -> Result<(String, String)> {
    let dark_value = tokens.resolved_value(path, Theme::Dark)?;
    let light_value = tokens.resolved_value(path, Theme::Light)?;
    let slint_type = match token_type {
        "color" => "color",
        "dimension" => "length",
        "duration" => "duration",
        "number" => "float",
        "fontWeight" => "int",
        "fontFamily" => "string",
        "typography" => "MellowTypeStyle",
        other => bail!("unsupported token type `{other}`"),
    };
    let dark_literal = slint_literal(token_type, &dark_value)?;
    let light_literal = slint_literal(token_type, &light_value)?;
    let value = if dark_literal == light_literal {
        dark_literal
    } else {
        format!("MellowTheme.is-dark ? {dark_literal} : {light_literal}")
    };
    Ok((slint_type.to_owned(), value))
}

fn slint_literal(token_type: &str, value: &Value) -> Result<String> {
    match token_type {
        "color" => {
            let text = as_str(value)?;
            crate::design_tokens::Rgba::parse_hex(text)?;
            Ok(text.to_owned())
        }
        "dimension" => pixel_length(as_str(value)?),
        "duration" => milliseconds(as_str(value)?),
        "number" | "fontWeight" => value
            .as_f64()
            .map(|number| number.to_string())
            .ok_or_else(|| anyhow!("expected a number, found {value}")),
        "fontFamily" => font_family(value),
        "typography" => type_style(value),
        other => bail!("unsupported token type `{other}`"),
    }
}

fn as_str(value: &Value) -> Result<&str> {
    value
        .as_str()
        .ok_or_else(|| anyhow!("expected a string, found {value}"))
}

fn pixel_length(text: &str) -> Result<String> {
    let number = text
        .strip_suffix("px")
        .ok_or_else(|| anyhow!("dimension `{text}` must be in px"))?;
    number
        .parse::<f64>()
        .map_err(|_| anyhow!("dimension `{text}` is not a number of px"))?;
    Ok(text.to_owned())
}

fn milliseconds(text: &str) -> Result<String> {
    let number = text
        .strip_suffix("ms")
        .ok_or_else(|| anyhow!("duration `{text}` must be in ms"))?;
    number
        .parse::<u32>()
        .map_err(|_| anyhow!("duration `{text}` is not a whole number of ms"))?;
    Ok(text.to_owned())
}

/// Slint takes one family name; the rest of the stack is the platform fallback's job.
fn font_family(value: &Value) -> Result<String> {
    let first_family = match value {
        Value::Array(families) => families.first().and_then(Value::as_str),
        Value::String(family) => Some(family.as_str()),
        _ => None,
    }
    .ok_or_else(|| anyhow!("font family must be a name or a list of names, found {value}"))?;
    Ok(format!("{first_family:?}"))
}

fn type_style(value: &Value) -> Result<String> {
    let field = |name: &str| {
        value
            .get(name)
            .ok_or_else(|| anyhow!("typography is missing `{name}`"))
    };
    let font_size_text = as_str(field("fontSize")?)?;
    let font_size_pixels: f64 = font_size_text
        .strip_suffix("px")
        .and_then(|number| number.parse().ok())
        .ok_or_else(|| anyhow!("fontSize `{font_size_text}` must be in px"))?;
    let line_height_multiplier = field("lineHeight")?
        .as_f64()
        .ok_or_else(|| anyhow!("lineHeight must be a unitless multiplier"))?;
    Ok(format!(
        "{{ font-family: {}, font-size: {}, font-weight: {}, line-height: {}px, letter-spacing: {} }}",
        font_family(field("fontFamily")?)?,
        pixel_length(font_size_text)?,
        slint_literal("fontWeight", field("fontWeight")?)?,
        // Rounded so 16 px × 1.375 gives exactly 22 px instead of float noise.
        (font_size_pixels * line_height_multiplier * 100.0).round() / 100.0,
        pixel_length(as_str(field("letterSpacing")?)?)?,
    ))
}

#[cfg(test)]
mod tests {
    use super::*;

    const SAMPLE_TOKENS: &str = r##"{
        "ref": { "$type": "color", "grey": { "$value": "#313338" }, "white": { "$value": "#FFFFFF" } },
        "color": { "$type": "color", "surface": { "chat": {
            "$value": "{ref.grey}", "$extensions": { "org.mellow.theme": { "light": "{ref.white}" } } } } },
        "space": { "$type": "dimension", "3xs": { "$value": "2px" } },
        "font": { "family": { "sans": { "$type": "fontFamily", "$value": ["Noto Sans", "sans-serif"] } },
                  "weight": { "regular": { "$type": "fontWeight", "$value": 400 } } },
        "type": { "message": { "$type": "typography", "$value": {
            "fontFamily": "{font.family.sans}", "fontSize": "16px", "fontWeight": "{font.weight.regular}",
            "lineHeight": 1.375, "letterSpacing": "0px" } } }
    }"##;

    #[test]
    fn generates_themed_colours_dimensions_and_type_styles() {
        let tokens = DesignTokens::parse(SAMPLE_TOKENS).unwrap();
        let slint = generate_slint_tokens(&tokens).unwrap();
        assert!(slint.contains(
            "out property <color> surface-chat: MellowTheme.is-dark ? #313338 : #FFFFFF;"
        ));
        assert!(slint.contains("out property <length> space-3xs: 2px;"));
        assert!(slint.contains("font-size: 16px, font-weight: 400, line-height: 22px"));
        assert!(
            !slint.contains("grey"),
            "raw palette tokens must not be exported"
        );
    }

    #[test]
    fn rejects_values_slint_cannot_represent() {
        assert!(pixel_length("1rem").is_err());
        assert!(milliseconds("0.2s").is_err());
        assert!(font_family(&Value::Null).is_err());
    }
}
