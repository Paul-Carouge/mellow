//! Turns resolved design tokens into plain Rust data for the GPUI desktop client (DESIGN.md §3.4),
//! and the icon files of `design/icons` into an `IconName` enum.
//!
//! The output holds no GPUI type, so it survives GPUI upgrades and its tests need no window. Colours
//! and shadows are the only values that differ per theme; they live in one `ThemeTokens` struct per
//! theme so switching theme swaps one reference.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;

use anyhow::{Context as _, Result, anyhow, bail, ensure};
use serde_json::Value;

use crate::css_tokens::EXPORTED_GROUPS;
use crate::design_tokens::{DesignTokens, Rgba, Theme, alias_target};

/// Durations reached through this group are animations: zero under reduced motion (DESIGN.md §2.8).
const ANIMATION_DURATION_PREFIX: &str = "motion.duration.";
/// Typography tokens the chat font size setting scales (DESIGN.md §2.4 "Scaling").
const CHAT_FONT_TYPE_PREFIXES: [&str; 2] = ["type.message", "type.code"];

/// Window widths at which the layout changes, as the web client sums them (`Shell.svelte`).
const NAVIGATOR_AND_SHEET_WIDTH_PATHS: [&str; 6] = [
    "size.sheet.inset",
    "component.navigator.strip-width",
    "component.sidebar.width",
    "size.sheet.inset",
    "size.chat.min-width",
    "size.sheet.inset",
];
const SIDE_SHEET_WIDTH_PATHS: [&str; 2] = ["component.side-sheet.width", "size.sheet.inset"];
const SEARCH_SHEET_WIDTH_PATHS: [&str; 2] = ["component.search.panel-width", "size.sheet.inset"];

const GENERATED_FILE_HEADER: &str = "\
// @generated by `cargo xtask tokens` from design/tokens.json. Do not edit by hand.
//! Design tokens as plain data (DESIGN.md §3.4). Lengths are logical pixels at 100 % zoom, colours
//! are `0xRRGGBBAA`, durations are milliseconds.
// Every token is exported for parity with the web client; each screen uses only its own.
#![allow(dead_code)]

/// A duration that animates: zero under reduced motion (DESIGN.md §2.8).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct AnimationDuration(pub u64);

/// A delay, display time or loop period: kept under reduced motion, or content would flash.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Delay(pub u64);

/// One layer of a box shadow, in logical pixels.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct ShadowLayer {
    pub color: u32,
    pub offset_x: f32,
    pub offset_y: f32,
    pub blur: f32,
    pub spread: f32,
}

/// A composite type style; `line_height` multiplies `font_size`.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct TypeToken {
    pub font_family: &'static [&'static str],
    pub font_size: f32,
    pub font_weight: u16,
    pub line_height: f32,
    pub letter_spacing: f32,
    pub scales_with_chat_font: bool,
}
";

const ICONS_FILE_HEADER: &str = "\
// @generated by `cargo xtask tokens` from the files in design/icons. Do not edit by hand.
//! The Phosphor icons of `design/icons`, embedded in the binary (DESIGN.md §2.9).
// One match arm per icon: long by nature, and generated.
#![allow(clippy::too_many_lines)]
";

pub fn generate_rust_tokens(tokens: &DesignTokens) -> Result<String> {
    let mut theme_fields = String::new();
    let mut dark_values = String::new();
    let mut light_values = String::new();
    let mut constants = String::new();
    let mut names = BTreeSet::new();
    for (path, token) in &tokens.tokens_by_path {
        let Some(group) = path.split('.').next() else {
            continue;
        };
        if !EXPORTED_GROUPS.contains(&group) {
            continue;
        }
        let field_name = path.replace(['.', '-'], "_");
        ensure!(
            names.insert(field_name.clone()),
            "token `{path}` collides with another token's Rust name `{field_name}`"
        );
        let dark = tokens.resolved_value(path, Theme::Dark)?;
        let light = tokens.resolved_value(path, Theme::Light)?;
        let themed_type = match token.token_type.as_str() {
            "color" => Some("u32"),
            "shadow" => Some("&'static [ShadowLayer]"),
            _ => None,
        };
        if let Some(rust_type) = themed_type {
            writeln!(theme_fields, "    pub {field_name}: {rust_type},")?;
            for (theme_value, output) in [(&dark, &mut dark_values), (&light, &mut light_values)] {
                let literal = themed_literal(&token.token_type, theme_value)
                    .with_context(|| format!("token `{path}`"))?;
                writeln!(output, "    {field_name}: {literal},")?;
            }
            continue;
        }
        ensure!(
            dark == light,
            "token `{path}` differs per theme, but only colours and shadows may"
        );
        let (rust_type, literal) =
            constant_type_and_literal(tokens, path, &token.token_type, &dark)
                .with_context(|| format!("token `{path}`"))?;
        writeln!(
            constants,
            "pub const {}: {rust_type} = {literal};",
            field_name.to_uppercase()
        )?;
    }

    let navigator = sum_of_lengths(tokens, &NAVIGATOR_AND_SHEET_WIDTH_PATHS)?;
    let side_sheet = navigator + sum_of_lengths(tokens, &SIDE_SHEET_WIDTH_PATHS)?;
    let search_sheet = navigator + sum_of_lengths(tokens, &SEARCH_SHEET_WIDTH_PATHS)?;

    let mut output = String::from(GENERATED_FILE_HEADER);
    writeln!(
        output,
        "\n/// Colours and shadows, the values that differ per theme.\n#[derive(Debug, Clone, Copy, PartialEq)]\npub struct ThemeTokens {{\n{theme_fields}}}"
    )?;
    writeln!(
        output,
        "\npub const DARK_THEME: ThemeTokens = ThemeTokens {{\n{dark_values}}};"
    )?;
    writeln!(
        output,
        "\npub const LIGHT_THEME: ThemeTokens = ThemeTokens {{\n{light_values}}};"
    )?;
    writeln!(output, "\n{constants}")?;
    writeln!(
        output,
        "/// Window widths, in logical pixels, from which the navigator, a docked side sheet and docked\n/// search results fit (DESIGN.md §4.2); summed from the pane tokens.\npub const BREAKPOINT_NAVIGATOR: f32 = {};\npub const BREAKPOINT_SIDE_SHEET: f32 = {};\npub const BREAKPOINT_SEARCH_SHEET: f32 = {};",
        float_literal(navigator),
        float_literal(side_sheet),
        float_literal(search_sheet)
    )?;
    Ok(output)
}

/// `icon_file_names` are the `*.svg` names of `design/icons`; `icons_directory_from_output` is the
/// path from the generated file to that directory, for `include_bytes!`.
pub fn generate_icon_names(
    icon_file_names: &[String],
    icons_directory_from_output: &str,
) -> Result<String> {
    let mut variants = BTreeMap::new();
    for file_name in icon_file_names {
        let stem = file_name
            .strip_suffix(".svg")
            .ok_or_else(|| anyhow!("icon `{file_name}` is not an .svg file"))?;
        ensure!(
            !stem.is_empty()
                && stem.chars().all(|character| character.is_ascii_lowercase()
                    || character.is_ascii_digit()
                    || character == '-')
                && stem.starts_with(|character: char| character.is_ascii_lowercase()),
            "icon `{file_name}` must be named in lowercase kebab-case"
        );
        let variant = pascal_case(stem);
        if let Some(previous) = variants.insert(variant.clone(), stem.to_owned()) {
            bail!("icons `{previous}` and `{stem}` both become `IconName::{variant}`");
        }
    }
    ensure!(!variants.is_empty(), "design/icons holds no icon");

    let mut enum_variants = String::new();
    let mut all_variants = String::new();
    let mut asset_paths = String::new();
    let mut from_asset_paths = String::new();
    let mut svg_bytes = String::new();
    for (variant, stem) in &variants {
        writeln!(enum_variants, "    {variant},")?;
        writeln!(all_variants, "        Self::{variant},")?;
        writeln!(
            asset_paths,
            "            Self::{variant} => \"icons/{stem}.svg\","
        )?;
        writeln!(
            from_asset_paths,
            "            \"icons/{stem}.svg\" => Some(Self::{variant}),"
        )?;
        writeln!(
            svg_bytes,
            "            Self::{variant} => include_bytes!(\"{icons_directory_from_output}/{stem}.svg\"),"
        )?;
    }
    let count = variants.len();
    let mut output = String::from(ICONS_FILE_HEADER);
    writeln!(
        output,
        "\n/// One variant per icon file, so a missing icon fails to compile.\n#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]\npub enum IconName {{\n{enum_variants}}}"
    )?;
    writeln!(
        output,
        "\nimpl IconName {{\n    pub const ALL: [Self; {count}] = [\n{all_variants}    ];\n\n    /// The path GPUI's `svg().path(…)` asks the asset source for.\n    #[must_use]\n    pub fn asset_path(self) -> &'static str {{\n        match self {{\n{asset_paths}        }}\n    }}\n\n    #[must_use]\n    pub fn from_asset_path(path: &str) -> Option<Self> {{\n        match path {{\n{from_asset_paths}            _ => None,\n        }}\n    }}\n\n    #[must_use]\n    pub fn svg_bytes(self) -> &'static [u8] {{\n        match self {{\n{svg_bytes}        }}\n    }}\n}}"
    )?;
    Ok(output)
}

/// `arrow-bend-up-left` → `ArrowBendUpLeft`.
fn pascal_case(kebab: &str) -> String {
    kebab
        .split('-')
        .map(|word| {
            let mut characters = word.chars();
            characters.next().map_or_else(String::new, |first| {
                first.to_ascii_uppercase().to_string() + characters.as_str()
            })
        })
        .collect()
}

fn themed_literal(token_type: &str, value: &Value) -> Result<String> {
    match token_type {
        "color" => color_literal(value),
        "shadow" => {
            let layers: Vec<&Value> = match value {
                Value::Array(layers) => layers.iter().collect(),
                layer => vec![layer],
            };
            let layers = layers
                .into_iter()
                .map(|layer| {
                    Ok(format!(
                        "ShadowLayer {{ color: {}, offset_x: {}, offset_y: {}, blur: {}, spread: {} }}",
                        color_literal(field(layer, "color")?)?,
                        float_literal(pixels(field(layer, "offsetX")?)?),
                        float_literal(pixels(field(layer, "offsetY")?)?),
                        float_literal(pixels(field(layer, "blur")?)?),
                        float_literal(pixels(field(layer, "spread")?)?),
                    ))
                })
                .collect::<Result<Vec<_>>>()?;
            Ok(format!("&[{}]", layers.join(", ")))
        }
        other => bail!("`{other}` tokens are not themed"),
    }
}

fn constant_type_and_literal(
    tokens: &DesignTokens,
    path: &str,
    token_type: &str,
    value: &Value,
) -> Result<(&'static str, String)> {
    Ok(match token_type {
        "dimension" => ("f32", float_literal(pixels(value)?)),
        "duration" => {
            let milliseconds = milliseconds(value)?;
            if alias_chain_reaches_animation(tokens, path)? {
                (
                    "AnimationDuration",
                    format!("AnimationDuration({milliseconds})"),
                )
            } else {
                ("Delay", format!("Delay({milliseconds})"))
            }
        }
        "number" => ("f32", float_literal(number(value)?)),
        "fontWeight" => ("u16", font_weight(value)?.to_string()),
        "fontFamily" => ("&[&str]", font_family_literal(value)?),
        "cubicBezier" => {
            let points = value
                .as_array()
                .filter(|points| points.len() == 4)
                .ok_or_else(|| anyhow!("expected four numbers, found {value}"))?
                .iter()
                .map(|point| number(point).map(float_literal))
                .collect::<Result<Vec<_>>>()?;
            ("[f32; 4]", format!("[{}]", points.join(", ")))
        }
        "typography" => (
            "TypeToken",
            format!(
                "TypeToken {{ font_family: {}, font_size: {}, font_weight: {}, line_height: {}, letter_spacing: {}, scales_with_chat_font: {} }}",
                font_family_literal(field(value, "fontFamily")?)?,
                float_literal(pixels(field(value, "fontSize")?)?),
                font_weight(field(value, "fontWeight")?)?,
                float_literal(number(field(value, "lineHeight")?)?),
                float_literal(pixels(field(value, "letterSpacing")?)?),
                CHAT_FONT_TYPE_PREFIXES
                    .iter()
                    .any(|prefix| path.starts_with(prefix)),
            ),
        ),
        other => bail!("unsupported token type `{other}`"),
    })
}

/// Whether `path` is, or aliases through, a `motion.duration.*` token. Literal component
/// durations (Melli's loops, the typing dots) are periods whose reduced-motion variant is drawn
/// still, so they stay delays, as in the web stylesheet.
fn alias_chain_reaches_animation(tokens: &DesignTokens, path: &str) -> Result<bool> {
    let mut current = path;
    // `resolved_value` already rejected cycles; the bound only keeps this loop obviously finite.
    for _ in 0..=tokens.tokens_by_path.len() {
        if current.starts_with(ANIMATION_DURATION_PREFIX) {
            return Ok(true);
        }
        let token = tokens
            .tokens_by_path
            .get(current)
            .ok_or_else(|| anyhow!("unknown token `{current}`"))?;
        match token.dark_value.as_str().and_then(alias_target) {
            Some(target) => current = target,
            None => return Ok(false),
        }
    }
    bail!("alias cycle at `{path}`")
}

fn sum_of_lengths(tokens: &DesignTokens, paths: &[&str]) -> Result<f64> {
    paths.iter().try_fold(0.0, |total, path| {
        Ok(total + pixels(&tokens.resolved_value(path, Theme::Dark)?)?)
    })
}

fn color_literal(value: &Value) -> Result<String> {
    let colour = Rgba::parse_hex(as_str(value)?)?;
    Ok(format!(
        "0x{:02X}{:02X}_{:02X}{:02X}",
        colour.red, colour.green, colour.blue, colour.alpha
    ))
}

fn pixels(value: &Value) -> Result<f64> {
    let text = as_str(value)?;
    text.strip_suffix("px")
        .ok_or_else(|| anyhow!("dimension `{text}` must be in px"))?
        .parse()
        .with_context(|| format!("dimension `{text}` is not a number"))
}

fn milliseconds(value: &Value) -> Result<u64> {
    let text = as_str(value)?;
    text.strip_suffix("ms")
        .ok_or_else(|| anyhow!("duration `{text}` must be in ms"))?
        .parse()
        .with_context(|| format!("duration `{text}` is not a whole number of milliseconds"))
}

fn font_weight(value: &Value) -> Result<u16> {
    value
        .as_u64()
        .and_then(|weight| u16::try_from(weight).ok())
        .ok_or_else(|| anyhow!("font weight {value} is not a whole number"))
}

fn font_family_literal(value: &Value) -> Result<String> {
    let families = value
        .as_array()
        .ok_or_else(|| anyhow!("expected a list of families, found {value}"))?
        .iter()
        .map(|family| Ok(format!("{:?}", as_str(family)?)))
        .collect::<Result<Vec<_>>>()?;
    Ok(format!("&[{}]", families.join(", ")))
}

/// `16` → `16.0`, `0.62` → `0.62`: always a float literal.
fn float_literal(value: f64) -> String {
    format!("{value:?}")
}

fn number(value: &Value) -> Result<f64> {
    value
        .as_f64()
        .ok_or_else(|| anyhow!("expected a number, found {value}"))
}

fn field<'a>(value: &'a Value, key: &str) -> Result<&'a Value> {
    value
        .get(key)
        .ok_or_else(|| anyhow!("missing `{key}` in {value}"))
}

fn as_str(value: &Value) -> Result<&str> {
    value
        .as_str()
        .ok_or_else(|| anyhow!("expected a string, found {value}"))
}

#[cfg(test)]
mod tests {
    use super::*;

    const SAMPLE_TOKENS: &str = r##"{
      "ref": { "white": { "$type": "color", "$value": "#ffffff" },
        "shadow-dark": { "$type": "color", "$value": "#0000003D" },
        "shadow-light": { "$type": "color", "$value": "#00000029" } },
      "color": { "surface": { "chat": { "$type": "color", "$value": "#221B23",
        "$extensions": { "org.mellow.theme": { "light": "{ref.white}" } } } } },
      "space": { "md": { "$type": "dimension", "$value": "16px" } },
      "size": { "sheet": { "inset": { "$type": "dimension", "$value": "8px" } },
        "chat": { "min-width": { "$type": "dimension", "$value": "480px" } } },
      "elevation": { "high": { "$type": "shadow", "$value": { "color": "{ref.shadow-dark}",
        "offsetX": "0px", "offsetY": "8px", "blur": "16px", "spread": "0px" },
        "$extensions": { "org.mellow.theme": { "light": { "color": "{ref.shadow-light}",
          "offsetX": "0px", "offsetY": "8px", "blur": "16px", "spread": "0px" } } } } },
      "motion": { "duration": { "settle": { "$type": "duration", "$value": "340ms" } },
        "delay": { "tooltip": { "$type": "duration", "$value": "500ms" } },
        "easing": { "settle": { "$type": "cubicBezier", "$value": [0.34, 1.3, 0.64, 1] } } },
      "font": { "family": { "sans": { "$type": "fontFamily", "$value": ["Figtree", "Noto Sans"] } },
        "weight": { "regular": { "$type": "fontWeight", "$value": 400 } } },
      "type": { "message": { "$type": "typography", "$value": {
          "fontFamily": "{font.family.sans}", "fontSize": "16px", "fontWeight": "{font.weight.regular}",
          "lineHeight": 1.5, "letterSpacing": "0px" } },
        "heading-lg": { "$type": "typography", "$value": {
          "fontFamily": "{font.family.sans}", "fontSize": "20px", "fontWeight": 700,
          "lineHeight": 1.3, "letterSpacing": "-0.2px" } } },
      "component": {
        "navigator": { "strip-width": { "$type": "dimension", "$value": "72px" } },
        "sidebar": { "width": { "$type": "dimension", "$value": "240px" } },
        "side-sheet": { "width": { "$type": "dimension", "$value": "240px" } },
        "search": { "panel-width": { "$type": "dimension", "$value": "400px" } },
        "dialog": { "enter-duration": { "$type": "duration", "$value": "{motion.duration.settle}" },
          "enter-scale": { "$type": "number", "$value": 0.96 } },
        "tooltip": { "delay": { "$type": "duration", "$value": "{motion.delay.tooltip}" } },
        "melli": { "float-duration": { "$type": "duration", "$value": "3200ms" } }
      }
    }"##;

    fn generated() -> String {
        generate_rust_tokens(&DesignTokens::parse(SAMPLE_TOKENS).unwrap()).unwrap()
    }

    #[test]
    fn colours_and_shadows_are_one_struct_per_theme() {
        let rust = generated();
        assert!(rust.contains("    pub color_surface_chat: u32,"));
        assert!(rust.contains(
            "DARK_THEME: ThemeTokens = ThemeTokens {\n    color_surface_chat: 0x221B_23FF,"
        ));
        assert!(rust.contains(
            "LIGHT_THEME: ThemeTokens = ThemeTokens {\n    color_surface_chat: 0xFFFF_FFFF,"
        ));
        assert!(rust.contains("    elevation_high: &[ShadowLayer { color: 0x0000_003D, offset_x: 0.0, offset_y: 8.0, blur: 16.0, spread: 0.0 }],"));
        assert!(rust.contains("    elevation_high: &[ShadowLayer { color: 0x0000_0029,"));
        assert!(!rust.contains("ref_"), "the raw palette stays private");
    }

    #[test]
    fn lengths_stay_in_pixels_and_numbers_are_floats() {
        let rust = generated();
        assert!(rust.contains("pub const SPACE_MD: f32 = 16.0;"));
        assert!(rust.contains("pub const COMPONENT_DIALOG_ENTER_SCALE: f32 = 0.96;"));
        assert!(
            rust.contains("pub const MOTION_EASING_SETTLE: [f32; 4] = [0.34, 1.3, 0.64, 1.0];")
        );
        assert!(rust.contains("pub const FONT_WEIGHT_REGULAR: u16 = 400;"));
    }

    #[test]
    fn durations_through_motion_duration_animate_and_the_others_are_delays() {
        let rust = generated();
        assert!(rust.contains(
            "pub const MOTION_DURATION_SETTLE: AnimationDuration = AnimationDuration(340);"
        ));
        assert!(rust.contains(
            "pub const COMPONENT_DIALOG_ENTER_DURATION: AnimationDuration = AnimationDuration(340);"
        ));
        assert!(rust.contains("pub const MOTION_DELAY_TOOLTIP: Delay = Delay(500);"));
        assert!(rust.contains("pub const COMPONENT_TOOLTIP_DELAY: Delay = Delay(500);"));
        assert!(rust.contains("pub const COMPONENT_MELLI_FLOAT_DURATION: Delay = Delay(3200);"));
    }

    #[test]
    fn type_tokens_resolve_their_aliases_and_flag_the_chat_font() {
        let rust = generated();
        assert!(rust.contains("pub const TYPE_MESSAGE: TypeToken = TypeToken { font_family: &[\"Figtree\", \"Noto Sans\"], font_size: 16.0, font_weight: 400, line_height: 1.5, letter_spacing: 0.0, scales_with_chat_font: true };"));
        assert!(rust.contains("font_size: 20.0, font_weight: 700, line_height: 1.3, letter_spacing: -0.2, scales_with_chat_font: false"));
    }

    #[test]
    fn breakpoints_are_summed_from_the_pane_tokens() {
        let rust = generated();
        assert!(rust.contains("pub const BREAKPOINT_NAVIGATOR: f32 = 816.0;"));
        assert!(rust.contains("pub const BREAKPOINT_SIDE_SHEET: f32 = 1064.0;"));
        assert!(rust.contains("pub const BREAKPOINT_SEARCH_SHEET: f32 = 1224.0;"));
    }

    #[test]
    fn only_colours_and_shadows_may_differ_per_theme() {
        let themed_length = SAMPLE_TOKENS.replace(
            r#""md": { "$type": "dimension", "$value": "16px" }"#,
            r#""md": { "$type": "dimension", "$value": "16px", "$extensions": { "org.mellow.theme": { "light": "12px" } } }"#,
        );
        let error = generate_rust_tokens(&DesignTokens::parse(&themed_length).unwrap())
            .unwrap_err()
            .to_string();
        assert!(error.contains("differs per theme"), "{error}");
    }

    #[test]
    fn icon_files_become_an_enum_with_their_bytes() {
        let rust = generate_icon_names(
            &["hash.svg".to_owned(), "arrow-bend-up-left.svg".to_owned()],
            "../icons",
        )
        .unwrap();
        assert!(rust.contains("pub enum IconName {\n    ArrowBendUpLeft,\n    Hash,\n}"));
        assert!(rust.contains("pub const ALL: [Self; 2] = ["));
        assert!(rust.contains("Self::Hash => \"icons/hash.svg\","));
        assert!(rust.contains("\"icons/arrow-bend-up-left.svg\" => Some(Self::ArrowBendUpLeft),"));
        assert!(rust.contains("Self::Hash => include_bytes!(\"../icons/hash.svg\"),"));
    }

    #[test]
    fn icon_names_must_be_kebab_case_svg_files() {
        for bad in ["Hash.svg", "hash.png", "1st.svg", "hash_tag.svg"] {
            assert!(
                generate_icon_names(&[bad.to_owned()], "..").is_err(),
                "{bad}"
            );
        }
        assert!(generate_icon_names(&[], "..").is_err());
    }
}
