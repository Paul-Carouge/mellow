//! The web favicon and the source of every app icon: Melli's still idle pose on a dusk tile
//! (DESIGN.md §2.10, ADR-0022), coloured from the mascot tokens so the logo never drifts from the
//! palette. Favicons do not animate. The maskable variant is the same tile without its rounded
//! corners, for launchers that cut their own shape (the installed web app on Android).

use anyhow::{Result, anyhow};

use crate::design_tokens::{DesignTokens, Rgba, Theme};

/// Same drawing as `web/src/components/Melli.svelte` (outline, puffs, eyes), without motion,
/// shadow or marks, centred on a rounded tile: a dusk gradient with a low apricot glow behind the
/// cloud. The tile fills the whole viewBox; macOS insets it into its 824/1024 grid (`app_icons.rs`).
const FAVICON_TEMPLATE: &str = r#"<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256">
  <!-- Generated by `cargo xtask tokens` from design/tokens.json. Do not edit by hand. -->
  <title>Mellow</title>
  <defs>
    <linearGradient id="sky" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="{tile-top}"/><stop offset="1" stop-color="{tile-bottom}"/>
    </linearGradient>
    <radialGradient id="glow" cx="0.5" cy="0.92" r="0.62">
      <stop offset="0" stop-color="{glow}" stop-opacity="{glow-opacity}"/><stop offset="1" stop-color="{glow}" stop-opacity="0"/>
    </radialGradient>
  </defs>
  <rect width="256" height="256" rx="{tile-radius}" fill="url(#sky)"/>
  <rect width="256" height="256" rx="{tile-radius}" fill="url(#glow)"/>
  <g transform="translate(128 128) scale(0.9) translate(-128 -124)">
    <g fill="{outline}">
      <circle cx="128" cy="124" r="68"/><circle cx="128" cy="78" r="36"/><circle cx="167.8" cy="101" r="36"/><circle cx="167.8" cy="147" r="36"/><circle cx="128" cy="170" r="36"/><circle cx="88.2" cy="147" r="36"/><circle cx="88.2" cy="101" r="36"/>
    </g>
    <g fill="{body}">
      <circle cx="128" cy="124" r="62"/><circle cx="128" cy="78" r="30"/><circle cx="167.8" cy="101" r="30"/><circle cx="167.8" cy="147" r="30"/><circle cx="128" cy="170" r="30"/><circle cx="88.2" cy="147" r="30"/><circle cx="88.2" cy="101" r="30"/>
    </g>
    <g fill="{ink}">
      <rect x="110" y="112" width="12" height="24" rx="6"/><rect x="134" y="112" width="12" height="24" rx="6"/>
    </g>
  </g>
</svg>
"#;

/// The favicon's own rounded corners, on the 256 grid.
const FAVICON_TILE_RADIUS: &str = "57";
/// Full bleed: the launcher of a maskable icon draws the shape. Melli reaches 29 % of the width
/// from the centre, inside the specification's 40 % safe zone, so no mask cuts it.
const MASKABLE_TILE_RADIUS: &str = "0";

/// Opaque colours, written as `#RRGGBB`.
const PLACEHOLDER_TO_TOKEN: [(&str, &str); 5] = [
    ("{outline}", "color.mascot.outline"),
    ("{body}", "color.mascot.body"),
    ("{ink}", "color.mascot.ink"),
    ("{tile-top}", "color.mascot.tile-top"),
    ("{tile-bottom}", "color.mascot.tile-bottom"),
];
/// The glow is translucent: SVG gets its colour and its opacity separately.
const GLOW_TOKEN: &str = "color.mascot.tile-glow";

pub fn generate_favicon(tokens: &DesignTokens) -> Result<String> {
    generate_tile(tokens, FAVICON_TILE_RADIUS)
}

pub fn generate_maskable_icon(tokens: &DesignTokens) -> Result<String> {
    generate_tile(tokens, MASKABLE_TILE_RADIUS)
}

fn generate_tile(tokens: &DesignTokens, tile_radius: &str) -> Result<String> {
    let mut svg = FAVICON_TEMPLATE.replace("{tile-radius}", tile_radius);
    for (placeholder, path) in PLACEHOLDER_TO_TOKEN {
        let colour = mascot_colour(tokens, path)?;
        if colour.alpha != u8::MAX {
            return Err(anyhow!("`{path}` must be opaque"));
        }
        svg = svg.replace(placeholder, &rgb_hex(colour));
    }
    let glow = mascot_colour(tokens, GLOW_TOKEN)?;
    svg = svg.replace("{glow}", &rgb_hex(glow)).replace(
        "{glow-opacity}",
        &format!("{:.3}", f64::from(glow.alpha) / 255.0),
    );
    Ok(svg)
}

/// The mascot is brand artwork, identical in both themes; the light value is the same.
fn mascot_colour(tokens: &DesignTokens, path: &str) -> Result<Rgba> {
    let value = tokens.resolved_value(path, Theme::Light)?;
    let text = value
        .as_str()
        .ok_or_else(|| anyhow!("`{path}` is not a colour"))?;
    Rgba::parse_hex(text)
}

fn rgb_hex(colour: Rgba) -> String {
    format!("#{:02X}{:02X}{:02X}", colour.red, colour.green, colour.blue)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn fills_every_part_from_the_mascot_tokens() {
        let tokens = DesignTokens::parse(
            r##"{ "color": { "mascot": { "$type": "color",
                "outline": { "$value": "#3F332E" },
                "body": { "$value": "#FFFAF3" }, "ink": { "$value": "#3F332D" },
                "tile-top": { "$value": "#4A3450" }, "tile-bottom": { "$value": "#140C15" },
                "tile-glow": { "$value": "#F2A46E66" } } } }"##,
        )
        .unwrap();
        let svg = generate_favicon(&tokens).unwrap();
        for colour in ["#3F332E", "#FFFAF3", "#3F332D"] {
            assert!(
                svg.contains(&format!("fill=\"{colour}\"")),
                "{colour} missing"
            );
        }
        for colour in ["#4A3450", "#140C15"] {
            assert!(
                svg.contains(&format!("stop-color=\"{colour}\"")),
                "{colour} missing"
            );
        }
        assert!(svg.contains(r##"stop-color="#F2A46E" stop-opacity="0.400""##));
        assert!(svg.contains(r#"rx="57""#));
        assert!(!svg.contains('{'), "a placeholder was left: {svg}");

        let maskable = generate_maskable_icon(&tokens).unwrap();
        assert!(maskable.contains(r#"rx="0""#));
        assert!(
            !maskable.contains('{'),
            "a placeholder was left: {maskable}"
        );
    }
}
