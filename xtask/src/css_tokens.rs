//! Turns resolved design tokens into CSS custom properties for the web client (DESIGN.md §3.4),
//! plus a Tailwind `@theme` block naming them, so utility classes only ever read tokens.

use std::fmt::Write as _;

use anyhow::{Context as _, Result, anyhow, bail};
use serde_json::Value;

use crate::design_tokens::{DesignTokens, Theme};

/// `ref.*` is the raw palette: components use semantic tokens only, as in Slint.
const EXPORTED_GROUPS: [&str; 9] = [
    "color",
    "component",
    "elevation",
    "font",
    "motion",
    "radius",
    "size",
    "space",
    "type",
];
const ROOT_FONT_SIZE_PIXELS: f64 = 16.0;

const GENERATED_FILE_HEADER: &str = "\
/* Generated by `cargo xtask tokens` from design/tokens.json. Do not edit by hand. */
/* Dark is the default theme (DESIGN.md §2); light follows the system or data-theme=\"light\". */
";

pub fn generate_css_tokens(tokens: &DesignTokens) -> Result<String> {
    let mut dark_declarations = String::new();
    let mut light_declarations = String::new();
    let mut reduced_motion_declarations = String::new();
    let mut theme_declarations = String::new();
    for (path, token) in &tokens.tokens_by_path {
        let Some(group) = path.split('.').next() else {
            continue;
        };
        if !EXPORTED_GROUPS.contains(&group) {
            continue;
        }
        let name = variable_name(path);
        let dark = css_values(
            &name,
            &token.token_type,
            &tokens.resolved_value(path, Theme::Dark)?,
        )
        .with_context(|| format!("token `{path}`"))?;
        let light = css_values(
            &name,
            &token.token_type,
            &tokens.resolved_value(path, Theme::Light)?,
        )
        .with_context(|| format!("token `{path}`"))?;
        for (variable, value) in &dark {
            writeln!(dark_declarations, "  {variable}: {value};")?;
        }
        for ((variable, light_value), (_, dark_value)) in light.iter().zip(&dark) {
            if light_value != dark_value {
                writeln!(light_declarations, "  {variable}: {light_value};")?;
            }
        }
        if token.token_type == "duration" {
            writeln!(reduced_motion_declarations, "    {name}: 0ms;")?;
        }
        if let Some(theme_name) = tailwind_theme_name(path) {
            writeln!(theme_declarations, "  {theme_name}: var({name});")?;
        }
    }
    let mut output = String::from(GENERATED_FILE_HEADER);
    writeln!(output, "\n:root {{\n{dark_declarations}}}")?;
    writeln!(
        output,
        "\n@media (prefers-color-scheme: light) {{\n  :root:not([data-theme=\"dark\"]) {{\n{}  }}\n}}",
        indent(&light_declarations)
    )?;
    writeln!(
        output,
        "\n:root[data-theme=\"light\"] {{\n{light_declarations}}}"
    )?;
    writeln!(
        output,
        "\n@media (prefers-reduced-motion: reduce) {{\n  :root {{\n{reduced_motion_declarations}  }}\n}}"
    )?;
    writeln!(output, "\n@theme inline {{\n{theme_declarations}}}")?;
    Ok(output)
}

fn indent(declarations: &str) -> String {
    let mut indented = String::new();
    for line in declarations.lines() {
        indented.push_str("  ");
        indented.push_str(line);
        indented.push('\n');
    }
    indented
}

/// `color.surface.chat` → `--mw-color-surface-chat`.
fn variable_name(path: &str) -> String {
    format!("--mw-{}", path.replace('.', "-"))
}

/// The Tailwind theme variable a token feeds, if any: `bg-surface-chat`, `rounded-md`,
/// `p-md`, `font-sans`, `shadow-low`. Component, size and type tokens stay `var(--mw-…)`.
fn tailwind_theme_name(path: &str) -> Option<String> {
    let (group, rest) = path.split_once('.')?;
    let rest = rest.replace('.', "-");
    match group {
        "color" => Some(format!("--color-{rest}")),
        "radius" => Some(format!("--radius-{rest}")),
        "space" => Some(format!("--spacing-{rest}")),
        "elevation" => Some(format!("--shadow-{rest}")),
        "font" => rest
            .strip_prefix("family-")
            .map(|family| format!("--font-{family}")),
        _ => None,
    }
}

/// One variable per token, except typography, which becomes one per property.
fn css_values(name: &str, token_type: &str, value: &Value) -> Result<Vec<(String, String)>> {
    let single = |css: String| Ok(vec![(name.to_owned(), css)]);
    match token_type {
        "color" => {
            let text = as_str(value)?;
            crate::design_tokens::Rgba::parse_hex(text)?;
            single(text.to_owned())
        }
        "dimension" => single(rem_length(as_str(value)?)?),
        "duration" => single(as_str(value)?.to_owned()),
        "number" | "fontWeight" => single(number(value)?),
        "fontFamily" => single(font_family(value)?),
        "cubicBezier" => {
            let points = value
                .as_array()
                .ok_or_else(|| anyhow!("expected four numbers, found {value}"))?
                .iter()
                .map(number)
                .collect::<Result<Vec<_>>>()?;
            single(format!("cubic-bezier({})", points.join(", ")))
        }
        "shadow" => single(shadow(value)?),
        "typography" => Ok(vec![
            (
                format!("{name}-font-family"),
                font_family(field(value, "fontFamily")?)?,
            ),
            (
                format!("{name}-font-size"),
                rem_length(as_str(field(value, "fontSize")?)?)?,
            ),
            (
                format!("{name}-font-weight"),
                number(field(value, "fontWeight")?)?,
            ),
            (
                format!("{name}-line-height"),
                number(field(value, "lineHeight")?)?,
            ),
            (
                format!("{name}-letter-spacing"),
                rem_length(as_str(field(value, "letterSpacing")?)?)?,
            ),
        ]),
        other => bail!("unsupported token type `{other}`"),
    }
}

fn field<'a>(value: &'a Value, key: &str) -> Result<&'a Value> {
    value
        .get(key)
        .ok_or_else(|| anyhow!("missing `{key}` in {value}"))
}

fn as_str(value: &Value) -> Result<&str> {
    value
        .as_str()
        .ok_or_else(|| anyhow!("expected a string, found {value}"))
}

fn number(value: &Value) -> Result<String> {
    value
        .as_f64()
        .map(|number| number.to_string())
        .ok_or_else(|| anyhow!("expected a number, found {value}"))
}

/// In `rem`, so browser zoom and text size settings scale the whole interface (DESIGN.md §3.4).
fn rem_length(text: &str) -> Result<String> {
    let pixels: f64 = text
        .strip_suffix("px")
        .ok_or_else(|| anyhow!("dimension `{text}` must be in px"))?
        .parse()
        .with_context(|| format!("dimension `{text}` is not a number"))?;
    if pixels == 0.0 {
        return Ok("0".to_owned());
    }
    Ok(format!("{}rem", pixels / ROOT_FONT_SIZE_PIXELS))
}

fn font_family(value: &Value) -> Result<String> {
    let families = value
        .as_array()
        .ok_or_else(|| anyhow!("expected a list of families, found {value}"))?
        .iter()
        .map(|family| {
            let family = as_str(family)?;
            Ok(if family.contains(' ') {
                format!("\"{family}\"")
            } else {
                family.to_owned()
            })
        })
        .collect::<Result<Vec<_>>>()?;
    Ok(families.join(", "))
}

/// A single layer or a list of layers.
fn shadow(value: &Value) -> Result<String> {
    let layers: Vec<&Value> = match value {
        Value::Array(layers) => layers.iter().collect(),
        layer => vec![layer],
    };
    let css_layers = layers
        .into_iter()
        .map(|layer| {
            Ok(format!(
                "{} {} {} {} {}",
                rem_length(as_str(field(layer, "offsetX")?)?)?,
                rem_length(as_str(field(layer, "offsetY")?)?)?,
                rem_length(as_str(field(layer, "blur")?)?)?,
                rem_length(as_str(field(layer, "spread")?)?)?,
                as_str(field(layer, "color")?)?,
            ))
        })
        .collect::<Result<Vec<_>>>()?;
    Ok(css_layers.join(", "))
}

#[cfg(test)]
mod tests {
    use super::*;

    fn tokens(json: &str) -> DesignTokens {
        DesignTokens::parse(json).unwrap()
    }

    #[test]
    fn generates_themed_variables_rem_lengths_and_the_tailwind_theme() {
        let css = generate_css_tokens(&tokens(
            r##"{
              "ref": { "white": { "$type": "color", "$value": "#ffffff" } },
              "color": { "surface": { "chat": { "$type": "color", "$value": "#313338",
                "$extensions": { "org.mellow.theme": { "light": "{ref.white}" } } } } },
              "space": { "md": { "$type": "dimension", "$value": "16px" } },
              "motion": { "duration": { "fast": { "$type": "duration", "$value": "100ms" } } },
              "type": { "body": { "$type": "typography", "$value": {
                "fontFamily": ["Figtree", "Noto Sans"], "fontSize": "14px", "fontWeight": 400,
                "lineHeight": 1.25, "letterSpacing": "0px" } } }
            }"##,
        ))
        .unwrap();
        assert!(css.contains("  --mw-color-surface-chat: #313338;"));
        assert!(
            css.contains("--mw-color-surface-chat: #ffffff;"),
            "light value"
        );
        assert!(!css.contains("--mw-ref-"), "the raw palette stays private");
        assert!(css.contains("--mw-space-md: 1rem;"));
        assert!(css.contains("--mw-type-body-font-family: Figtree, \"Noto Sans\";"));
        assert!(css.contains("--mw-type-body-font-size: 0.875rem;"));
        assert!(
            css.contains("    --mw-motion-duration-fast: 0ms;"),
            "reduced motion"
        );
        assert!(css.contains("  --color-surface-chat: var(--mw-color-surface-chat);"));
        assert!(css.contains("  --spacing-md: var(--mw-space-md);"));
    }

    #[test]
    fn rejects_values_css_cannot_take() {
        assert!(rem_length("1em").is_err());
        assert!(css_values("--x", "color", &Value::from("red")).is_err());
    }
}
