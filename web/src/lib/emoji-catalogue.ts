function parseEntry(category: EmojiCategoryId, entry: string): CatalogueEmoji {
  const separator = entry.indexOf(" ");
  const emoji = entry.slice(0, separator);
  const words = entry.slice(separator + 1).replace("|", " ");
  return { emoji, category, keywords: words.split(" ").filter(Boolean) };
}

export const EMOJI_CATALOGUE: readonly CatalogueEmoji[] = EMOJI_CATEGORY_IDS.flatMap((category) =>
  RAW_CATALOGUE[category].map((entry) => parseEntry(category, entry)),
);

const FOLDED_KEYWORDS = new Map(
  EMOJI_CATALOGUE.map((entry) => [entry.emoji, entry.keywords.map(foldForSearch)] as const),
);

/**
 * Emoji whose words start with every word of the query, in catalogue order; an exact word comes
 * first. An empty query finds nothing (the picker then shows the categories).
 */
export function searchEmoji(query: string): CatalogueEmoji[] {
  const terms = foldForSearch(query).split(/\s+/u).filter(Boolean);
  if (terms.length === 0) {
    return [];
  }
  const matches = EMOJI_CATALOGUE.filter((entry) => {
    const words = FOLDED_KEYWORDS.get(entry.emoji) ?? [];
    return terms.every((term) => words.some((word) => word.startsWith(term)));
  });
  const isExact = (entry: CatalogueEmoji) =>
    terms.every((term) => (FOLDED_KEYWORDS.get(entry.emoji) ?? []).includes(term));
  return [...matches.filter(isExact), ...matches.filter((entry) => !isExact(entry))];
}
